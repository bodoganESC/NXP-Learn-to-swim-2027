#!/bin/bash

host_alias="dock"
host_address="0.0.0.0"
host_port="2222"
host_user="t"

if [[ -f ~/.ssh/id_rsa ]]; then
  echo "Local ssh keyfile .ssh/id_rsa exists"
else
  echo ".ssh/id_rsa does not exist, generating a key..."
  ssh-keygen -t rsa -b 4096 -C "AutoGeneratedForEasyDockerAccess"
fi

# Check if the host already exists in the .ssh/config file
if ! grep -q "^Host $host_alias$" ~/.ssh/config; then
   # Add the host to the .ssh/config file
   echo "Host $host_alias" >> ~/.ssh/config
   echo "   HostName $host_address" >> ~/.ssh/config
   echo "   Port $host_port" >> ~/.ssh/config
   echo "   User $host_user" >> ~/.ssh/config
   echo "   IdentityFile ~/.ssh/id_rsa" >> ~/.ssh/config
   echo "   StrictHostKeyChecking no" >> ~/.ssh/config
   echo "" >> ~/.ssh/config
   echo "Docker host alias added successfully in .ssh/config file... OK"
else
   echo "Docker host alias already exists in the .ssh/config file... OK"
fi

if [ 1 = `ssh-copy-id -n dock 2>&1 | grep ssh-rsa | wc -l` ]; then 
  echo "**************************************************"
  echo "*****Use the following password if asked: testtest"
  echo "**************************************************"
  ssh-copyid dock
  if [ $? = 1 ]; then 
     echo "Installing the local ssh key into docker container failed. Did you provide the password? (password: testtest)";
     exit 
  else 
     echo "Docker ssh key installed for easy ssh/scp access... OK"; 
  fi
else 
    echo "local ssh key seems to be authorized in the target docker container... OK"; 
fi

echo "Extracting, cleaning and copying files into target docker container..."
read -n1 -s -p "Press any key to continue if you are sure... (it MAY OVERWRITE files in container that you worked on...)"

7z x pixy2_interfaces.7z # extragere arhiva
rm -rf pixy2_interfaces/.git # stergere info git pentru a nu corupe istoricul git din container 
scp -r pixy2_interfaces dock:/home/t/ros2ws/src/pixy2_interfaces
rm -rf pixy2_interfaces

7z x pixy_sim.7z # extragere arhiva
rm -rf pixy_sim/.git # pentru a nu corupe istoricul git din container 
scp -r pixy_sim dock:/home/t/ros2ws/src/pixy_sim
rm -rf pixy_sim

7z x nxp_cup_vision.7z # extragere arhiva
rm -rf nxp_cup_vision/.git # pentru a nu corupe istoricul git din container 
scp -r nxp_cup_vision dock:/home/t/ros2ws/src/nxp_cup_vision
rm -rf nxp_cup_vision

ssh dock "mkdir -p ~/ros2ws/nxp_fuel/models/Raceway3/meshes"
scp ./modelt.sdf dock:~/ros2ws/nxp_fuel/models/Raceway3/model.sdf    # model pista
scp ./modelt.config dock:~/ros2ws/nxp_fuel/models/Raceway3/model.config    # config model pista
scp ./Track.dae dock:~/ros2ws/nxp_fuel/models/Raceway3/meshes/Track.dae #traseul printat din laborator, momentan fara simbolul de start, daca il deschideti cu blender il puteti edita...)
scp ./gen_params.json dock:~/ros2ws/src/sim_ignition_bringup/config/gen_params.json #reconfigurare lansare noduri... pozitie si orientare masina + altele...
scp ./model.sdf dock:~/ros2ws/nxp_fuel/models/Buggy3/model.sdf    # model masina reparat si completat cu o reprezentare simplista a camerei, adjustati pozitionare/orientarea dupa preferinta... fov e reglat aproape de realitate
scp ./gen.world.jinja dock:~/ros2ws/nxp_fuel/worlds/gen.world.jinja   # e dezajctivata generarea umbrelor, foarte important altfel se pare ca pe unele masini randeaza defectuos traseul

ssh dock ". ~/.bashrc.sh; cd /home/t/ros2ws/; colcon build --cmake-args -DCMAKE_BUILD_TYPE=Release --packages-select pixy2_interfaces; colcon build --cmake-args -DCMAKE_BUILD_TYPE=Release --packages-select pixy_sim"

#echo "./run.sh & ros2 run pixy_sim pixy"

